const systemLang = typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("it") ? "it" : "en";
let lang: "it" | "en" = systemLang;

/** Follows the desktop's language; anything but it/en falls back to the system's. */
export function setLanguage(l: string | undefined): boolean {
  const next = l === "it" || l === "en" ? l : systemLang;
  const changed = next !== lang;
  lang = next;
  return changed;
}

/** The speech recognizer's locale for the app language. */
export function speechLocale(): string {
  return lang === "it" ? "it-IT" : "en-US";
}

export type Key = keyof typeof it;

export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = (lang === "it" ? it : en)[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
